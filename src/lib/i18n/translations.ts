export type TranslationKey = keyof typeof de;

export function t(
  key: string,
  menuLocale: MenuLocale,
  isEnglish: boolean,
  vars?: Record<string, string | number>
): string {
  const locale: Locale = isEnglish ? "en" : menuLocale;
  const table = translations[locale] ?? translations.de;
  let text = table[key] ?? translations.en[key] ?? translations.de[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** @deprecated Use t(key, menuLocale, isEnglish) */
export function tLocale(
  key: string,
  locale: Locale,
  vars?: Record<string, string | number>
): string {
  return t(key, locale === "en" ? "de" : locale, locale === "en", vars);
}

export function orderStatusHeadlineKey(
  status: string,
  paymentStatus: string
): TranslationKey {
  if (status === "rejected") return "order.headline.rejected";
  if (status === "cancelled") return "order.headline.cancelled";
  if (paymentStatus === "paid") {
    if (status === "delivered") return "order.headline.enjoy";
    if (status === "ready") return "order.headline.readyPickup";
    return "order.headline.paymentReceived";
  }
  switch (status) {
    case "pending":
      return "order.headline.received";
    case "accepted":
      return "order.headline.accepted";
    case "preparing":
      return "order.headline.preparing";
    case "ready":
      return "order.headline.readyTable";
    case "delivered":
      return "order.headline.delivered";
    default:
      return "order.headline.placed";
  }
}

